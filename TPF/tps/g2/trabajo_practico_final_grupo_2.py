#definicion de la funcion para buscar proveedores
def buscar_proveedores(material, criterio):

#apertura y lectura de datos de proveedores
    archivo = open("/content/proveedores_materiales.csv", "r", encoding="utf-8")

    lector = csv.reader(archivo)
    encabezados = next(lector)

    proveedores = []

    for fila in lector:
        if fila[1].lower() == material.lower():
            proveedores.append(fila)

    archivo.close()

#filtrado y ordenamiento
    if criterio == "calidad":

        for i in range(len(proveedores)):
            posicion_mayor = i

            for j in range(i + 1, len(proveedores)):
                if float(proveedores[j][3]) > float(proveedores[posicion_mayor][3]):
                    posicion_mayor = j

            auxiliar = proveedores[i]
            proveedores[i] = proveedores[posicion_mayor]
            proveedores[posicion_mayor] = auxiliar

#ordenamiento por precio
    elif criterio == "precio":

        for i in range(len(proveedores)):
            posicion_menor = i

            for j in range(i + 1, len(proveedores)):
                if float(proveedores[j][2]) < float(proveedores[posicion_menor][2]):
                    posicion_menor = j

            auxiliar = proveedores[i]
            proveedores[i] = proveedores[posicion_menor]
            proveedores[posicion_menor] = auxiliar

#ordenamiento por distancia
    elif criterio == "distancia":

        for i in range(len(proveedores)):
            posicion_menor = i

            for j in range(i + 1, len(proveedores)):
                if float(proveedores[j][5]) < float(proveedores[posicion_menor][5]):
                    posicion_menor = j

            auxiliar = proveedores[i]
            proveedores[i] = proveedores[posicion_menor]
            proveedores[posicion_menor] = auxiliar

    else:
        print("Criterio de ordenamiento no valido.")
        return []

#retornar lista de proveedores
    return proveedores

